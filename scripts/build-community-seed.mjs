// Turns supabase/seed/community-starters.json into a SQL file you paste into the database's
// SQL editor once. Safe to re-run: a starter is skipped if a prompt with the same title exists.
//   node scripts/build-community-seed.mjs  ->  supabase/seed/community-starters.sql
import { readFileSync, writeFileSync } from "node:fs";

const rows = JSON.parse(readFileSync("supabase/seed/community-starters.json", "utf8"));
const q = (s) => (s == null ? "NULL" : `'${String(s).replace(/'/g, "''")}'`);
const json = (o) => (o == null ? "NULL" : `${q(JSON.stringify(o))}::jsonb`);

const values = rows.map(
  (r) =>
    `  (${q(r.title)}, ${q(r.style)}, ${json(r.vocal)}, ${q(r.exclude)}, ARRAY[${q(r.genre)}]::text[], ${q(r.note)})`,
);

const sql = `-- Band Blender community starters: ${rows.length} original style prompts, one or more per genre.
-- Generated by scripts/build-community-seed.mjs. Paste into the SQL editor and run once.
-- Re-running is safe: titles that already exist are skipped. No artist names, no user attached.
INSERT INTO public.public_prompts (title, style_tag, vocal_prompt, exclude_styles, genre_tags, recipe_note)
SELECT v.title, v.style_tag, v.vocal_prompt, v.exclude_styles, v.genre_tags, v.recipe_note
FROM (VALUES
${values.join(",\n")}
) AS v(title, style_tag, vocal_prompt, exclude_styles, genre_tags, recipe_note)
WHERE NOT EXISTS (SELECT 1 FROM public.public_prompts p WHERE p.title = v.title);
`;
writeFileSync("supabase/seed/community-starters.sql", sql);
console.log(`supabase/seed/community-starters.sql: ${rows.length} starters`);
