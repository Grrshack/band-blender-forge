// Builds the extension's bundled helper and the store zip.
//   node scripts/build-extension.mjs        -> extension/live.js
// The zip for the Chrome Web Store is made from the extension/ folder (manifest.json at the top).
import { build } from "esbuild";

await build({
  entryPoints: ["extension-src/live.ts"],
  outfile: "extension/live.js",
  bundle: true,
  format: "iife",
  target: "chrome110",
  minify: false,
  legalComments: "none",
  banner: { js: "// Generated by scripts/build-extension.mjs from src/lib (pre-flight checks). Do not edit by hand." },
});
console.log("extension/live.js built");
